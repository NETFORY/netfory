// Детерминированная «тонированная» обложка для витрин топ-приложений и магазина.
//
// Раньше палитра брала насыщенные hsl(52% / 58%) — цветные плитки выбивались
// из тёмной темы NETFORY. Теперь оттенок остаётся детерминированным (POKER
// всегда бирюзовый, docs всегда янтарный), но насыщенность и светлота сильно
// снижены, а второй стоп — почти чёрный. Получаем «tinted-dark → near-black»:
// карточки остаются различимыми, но живут внутри тёмно-графитовой палитры UI.
export function coverStyle(id: string): { background: string } {
  let h = 0
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) % 360
  const h2 = (h + 24) % 360
  return {
    background:
      `linear-gradient(140deg,` +
      ` hsl(${h}, 28%, 20%) 0%,` +
      ` hsl(${h2}, 20%, 12%) 55%,` +
      ` #0d1113 100%)`,
  }
}
